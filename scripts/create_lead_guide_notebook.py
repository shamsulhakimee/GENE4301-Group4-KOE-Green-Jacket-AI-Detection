# Section 6: Sample ROS2 BPU Detector Node
cells.append({"cell_type":"markdown","metadata":{},"source":[
 "### Sample ROS2 Humble BPU Detector Node (`bpu_detector_node.py`)\n",
 "\n",
 "```python\n",
 "import rclpy\n",
 "from rclpy.node import Node\n",
 "from sensor_msgs.msg import Image\n",
 "from std_msgs.msg import String\n",
 "from cv_bridge import CvBridge\n",
 "import cv2\n",
 "import numpy as np\n",
 "# Horizon BPU Python runtime\n",
 "from hobot_dnn import pyeasy_dnn as dnn\n",
 "\n",
 "class BPUJacketDetectorNode(Node):\n",
 "    def __init__(self):\n",
 "        super().__init__('bpu_jacket_detector_node')\n",
 "        \n",
 "        # Declare ROS2 Parameters\n",
 "        self.declare_parameter('model_path', 'models/koe_green_jacket_yolov8n.bin')\n",
 "        self.declare_parameter('conf_threshold', 0.50)\n",
 "        self.declare_parameter('iou_threshold', 0.45)\n",
 "        \n",
 "        model_path = self.get_parameter('model_path').get_parameter_value().string_value\n",
 "        self.conf_thresh = self.get_parameter('conf_threshold').get_parameter_value().double_value\n",
 "        self.iou_thresh = self.get_parameter('iou_threshold').get_parameter_value().double_value\n",
 "        \n",
 "        # Load BPU model\n",
 "        self.get_logger().info(f'Loading BPU model from: {model_path}')\n",
 "        self.models = dnn.load(model_path)\n",
 "        self.model = self.models[0]\n",
 "        \n",
 "        self.bridge = CvBridge()\n",
 "        \n",
 "        # ROS2 Subscriptions and Publishers\n",
 "        self.sub_image = self.create_subscription(\n",
 "            Image, '/image_raw', self.image_callback, 10\n",
 "        )\n",
 "        self.pub_status = self.create_publisher(String, '/workshop/access_status', 10)\n",
 "        self.pub_annotated = self.create_publisher(Image, '/koe/image_annotated', 10)\n",
 "        \n",
 "        self.get_logger().info('BPU Jacket Detector Node initialized in ROS2 Humble.')\n",
 "\n",
 "    def image_callback(self, msg):\n",
 "        cv_frame = self.bridge.imgmsg_to_cv2(msg, desired_encoding='bgr8')\n",
 "        h, w, _ = cv_frame.shape\n",
 "        \n",
 "        # 1. Preprocess: Resize to 640x640 (letterbox)\n",
 "        resized = cv2.resize(cv_frame, (640, 640))\n",
 "        input_tensor = np.expand_dims(resized, axis=0) # [1, 640, 640, 3]\n",
 "        \n",
 "        # 2. Hardware BPU Inference\n",
 "        outputs = self.model.forward(input_tensor)\n",
 "        \n",
 "        # 3. Postprocess detections & evaluate compliance\n",
 "        # (YOLOv8 decode strides, score thresholding, NMS)\n",
 "        jacket_detected = len(outputs) > 0 # logic placeholder for parsed detections\n",
 "        \n",
 "        status_msg = String()\n",
 "        if jacket_detected:\n",
 "            status_msg.data = 'AUTHORIZED: KOE_GREEN_JACKET_DETECTED'\n",
 "            cv2.putText(cv_frame, 'ACCESS GRANTED - KOE JACKET VERIFIED', (30, 50),\n",
 "                        cv2.FONT_HERSHEY_SIMPLEX, 1.0, (0, 255, 0), 2)\n",
 "        else:\n",
 "            status_msg.data = 'DENIED: NO_KOE_JACKET'\n",
 "            cv2.putText(cv_frame, 'ACCESS DENIED - NO KOE JACKET', (30, 50),\n",
 "                        cv2.FONT_HERSHEY_SIMPLEX, 1.0, (0, 0, 255), 2)\n",
 "        \n",
 "        self.pub_status.publish(status_msg)\n",
 "        self.pub_annotated.publish(self.bridge.cv2_to_imgmsg(cv_frame, encoding='bgr8'))\n",
 "\n",
 "def main(args=None):\n",
 "    rclpy.init(args=args)\n",
 "    node = BPUJacketDetectorNode()\n",
 "    rclpy.spin(node)\n",
 "    node.destroy_node()\n",
 "    rclpy.shutdown()\n",
 "```\n",
]})

